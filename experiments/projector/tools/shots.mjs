// node tools/shots.mjs <set> <outdir> : rest, mid-spin, mid-change, mid-open (p~0.4), open
import { mkdirSync } from 'node:fs';
import { launch, open, shot, sleep, drag } from './lib.mjs';
const set = process.argv[2] || 'bonnet', out = process.argv[3] || 'media';
mkdirSync(out, { recursive: true });
const b = await launch();
const { page, logs } = await open(b, set, {});
await shot(page, `${out}/${set}-1-rest.jpg`);
const d = await drag(page, 100, 700, 300, 700, 260, 10);
await sleep(30);
await shot(page, `${out}/${set}-2-spin.jpg`);
await d.end();
await sleep(1400);
await page.click('#next');
await sleep(150);
await shot(page, `${out}/${set}-3-change.jpg`);
await sleep(1400);
await page.evaluate(() => window.__pj.open());
await sleep(60);
await page.evaluate(() => window.__pj.hold(0.4));
await sleep(200);
await shot(page, `${out}/${set}-4-open-mid.jpg`);
await page.evaluate(() => window.__pj.hold(0.7));
await sleep(200);
await shot(page, `${out}/${set}-4b-open-mid.jpg`);
await page.evaluate(() => window.__pj.open());
await sleep(2200);
await shot(page, `${out}/${set}-5-open.jpg`);
console.log('handed', await page.evaluate(() => window.__pj.handed));
console.log(logs.filter((l) => !/vite|404/.test(l)).join('\n'));
await b.close();
